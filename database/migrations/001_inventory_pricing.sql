CREATE TABLE public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  email text NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND length(email) BETWEEN 3 AND 254),
  password_hash text NOT NULL CHECK (length(password_hash) > 0),
  role text NOT NULL CHECK (role IN ('admin', 'staff')),
  is_active boolean NOT NULL DEFAULT true,
  session_version integer NOT NULL DEFAULT 1 CHECK (session_version > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX categories_name_unique ON public.categories (lower(btrim(name)));

CREATE TABLE public.products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE CHECK (sku = upper(btrim(sku)) AND length(sku) BETWEEN 1 AND 64),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
  category_id integer NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  base_price numeric(14,2) NOT NULL CHECK (base_price BETWEEN 0 AND 999999999999.99),
  current_price numeric(14,2) NOT NULL CHECK (current_price BETWEEN 0 AND 999999999999.99),
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX products_category_idx ON public.products(category_id);

CREATE TABLE public.pricing_rules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL UNIQUE REFERENCES public.products(id) ON DELETE RESTRICT,
  low_stock integer NOT NULL CHECK (low_stock >= 0),
  high_stock integer NOT NULL CHECK (high_stock > low_stock),
  increase_percent numeric(7,2) NOT NULL DEFAULT 0 CHECK (increase_percent BETWEEN 0 AND 99999.99),
  discount_percent numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
  min_price numeric(14,2) NOT NULL CHECK (min_price BETWEEN 0 AND 999999999999.99),
  max_price numeric(14,2) NOT NULL CHECK (max_price BETWEEN min_price AND 999999999999.99),
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.stock_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  type text NOT NULL CHECK (type IN ('IN', 'SALE', 'RETURN', 'ADJUST_IN', 'ADJUST_OUT', 'DAMAGE')),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(14,2) NOT NULL CHECK (unit_price BETWEEN 0 AND 999999999999.99),
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  note text,
  related_movement_id integer REFERENCES public.stock_movements(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (type NOT IN ('ADJUST_IN', 'ADJUST_OUT', 'DAMAGE') OR length(btrim(note)) > 0 AND note IS NOT NULL),
  CHECK ((type = 'RETURN') = (related_movement_id IS NOT NULL))
);
CREATE INDEX stock_movements_product_time_idx ON public.stock_movements(product_id, created_at DESC);
CREATE INDEX stock_movements_user_time_idx ON public.stock_movements(user_id, created_at DESC);
CREATE INDEX stock_movements_related_idx ON public.stock_movements(related_movement_id) WHERE related_movement_id IS NOT NULL;

CREATE TABLE public.stock_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('RETURN', 'DAMAGE')),
  product_id integer NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  reason text NOT NULL CHECK (length(btrim(reason)) > 0),
  related_movement_id integer REFERENCES public.stock_movements(id) ON DELETE RESTRICT,
  requested_by integer NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
  reviewed_by integer REFERENCES public.users(id) ON DELETE RESTRICT,
  reviewed_at timestamptz,
  review_note text,
  movement_id integer UNIQUE REFERENCES public.stock_movements(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((type = 'RETURN') = (related_movement_id IS NOT NULL)),
  CHECK (
    (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND movement_id IS NULL) OR
    (status = 'APPROVED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND movement_id IS NOT NULL) OR
    (status = 'REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND movement_id IS NULL)
  )
);
CREATE INDEX stock_requests_status_time_idx ON public.stock_requests(status, created_at DESC);
CREATE INDEX stock_requests_user_time_idx ON public.stock_requests(requested_by, created_at DESC);
CREATE INDEX stock_requests_product_idx ON public.stock_requests(product_id);
CREATE INDEX stock_requests_related_idx ON public.stock_requests(related_movement_id) WHERE related_movement_id IS NOT NULL;
CREATE INDEX stock_requests_reviewer_idx ON public.stock_requests(reviewed_by) WHERE reviewed_by IS NOT NULL;

CREATE TABLE public.price_history (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  old_price numeric(14,2) NOT NULL CHECK (old_price BETWEEN 0 AND 999999999999.99),
  new_price numeric(14,2) NOT NULL CHECK (new_price BETWEEN 0 AND 999999999999.99),
  reason text NOT NULL CHECK (length(btrim(reason)) > 0),
  changed_by integer REFERENCES public.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (old_price <> new_price)
);
CREATE INDEX price_history_product_time_idx ON public.price_history(product_id, created_at DESC);
CREATE INDEX price_history_user_idx ON public.price_history(changed_by) WHERE changed_by IS NOT NULL;

-- Validate actors at creation time; changing a staff member's role must not rewrite history.
CREATE FUNCTION public.validate_stock_movement() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  actor_role text;
  original public.stock_movements%ROWTYPE;
  returned bigint;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'Stock history is immutable; create a reversing movement';
  END IF;
  SELECT role INTO actor_role FROM public.users WHERE id = NEW.user_id AND is_active = true;
  IF actor_role IS NULL OR (NEW.type = 'SALE' AND actor_role <> 'staff') OR (NEW.type <> 'SALE' AND actor_role <> 'admin') THEN
    RAISE EXCEPTION 'Role is not allowed to create this movement';
  END IF;
  IF NEW.type = 'RETURN' THEN
    SELECT * INTO original FROM public.stock_movements WHERE id = NEW.related_movement_id FOR UPDATE;
    IF NOT FOUND OR original.type <> 'SALE' OR original.product_id <> NEW.product_id OR original.unit_price <> NEW.unit_price THEN
      RAISE EXCEPTION 'Return must match the original sale product and price';
    END IF;
    SELECT COALESCE(sum(quantity), 0) INTO returned FROM public.stock_movements WHERE related_movement_id = original.id AND type = 'RETURN';
    IF returned + NEW.quantity > original.quantity THEN
      RAISE EXCEPTION 'Returned quantity exceeds the original sale';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.validate_stock_movement() FROM PUBLIC;
CREATE TRIGGER stock_movement_guard BEFORE INSERT OR UPDATE OR DELETE ON public.stock_movements FOR EACH ROW EXECUTE FUNCTION public.validate_stock_movement();

CREATE FUNCTION public.validate_stock_request() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  original public.stock_movements%ROWTYPE;
  approved public.stock_movements%ROWTYPE;
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Request history cannot be deleted'; END IF;
  IF TG_OP = 'INSERT' AND NEW.status <> 'PENDING' THEN RAISE EXCEPTION 'New requests must be pending'; END IF;
  IF TG_OP = 'UPDATE' THEN
    IF OLD.status <> 'PENDING' OR NEW.status NOT IN ('APPROVED', 'REJECTED') THEN RAISE EXCEPTION 'Request can only be reviewed once'; END IF;
    IF ROW(NEW.type, NEW.product_id, NEW.quantity, NEW.reason, NEW.related_movement_id, NEW.requested_by, NEW.created_at)
       IS DISTINCT FROM ROW(OLD.type, OLD.product_id, OLD.quantity, OLD.reason, OLD.related_movement_id, OLD.requested_by, OLD.created_at) THEN
      RAISE EXCEPTION 'Request details cannot change during review';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.users WHERE id = NEW.reviewed_by AND role = 'admin' AND is_active = true) THEN
      RAISE EXCEPTION 'Only active admins may review requests';
    END IF;
  END IF;
  IF TG_OP = 'INSERT' AND NOT EXISTS (SELECT 1 FROM public.users WHERE id = NEW.requested_by AND is_active = true) THEN
    RAISE EXCEPTION 'Requester must be active';
  END IF;
  IF NEW.type = 'RETURN' THEN
    SELECT * INTO original FROM public.stock_movements WHERE id = NEW.related_movement_id;
    IF NOT FOUND OR original.type <> 'SALE' OR original.product_id <> NEW.product_id OR NEW.quantity > original.quantity THEN
      RAISE EXCEPTION 'Return request must refer to a matching sale';
    END IF;
    IF TG_OP = 'INSERT' AND EXISTS (SELECT 1 FROM public.users WHERE id = NEW.requested_by AND role = 'staff') AND original.user_id <> NEW.requested_by THEN
      RAISE EXCEPTION 'Staff may only request returns for their own sales';
    END IF;
  END IF;
  IF NEW.status = 'APPROVED' THEN
    SELECT * INTO approved FROM public.stock_movements WHERE id = NEW.movement_id;
    IF NOT FOUND OR approved.type <> NEW.type OR approved.product_id <> NEW.product_id OR approved.quantity <> NEW.quantity
       OR approved.user_id <> NEW.reviewed_by OR approved.related_movement_id IS DISTINCT FROM NEW.related_movement_id THEN
      RAISE EXCEPTION 'Approved request must match its resulting movement';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.validate_stock_request() FROM PUBLIC;
CREATE TRIGGER stock_request_guard BEFORE INSERT OR UPDATE OR DELETE ON public.stock_requests FOR EACH ROW EXECUTE FUNCTION public.validate_stock_request();

-- The Node server uses PostgreSQL credentials. Browser clients get no direct table access.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pricing_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.price_history ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE client_role text;
BEGIN
  FOREACH client_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = client_role) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.users, public.categories, public.products, public.pricing_rules, public.stock_movements, public.stock_requests, public.price_history FROM %I', client_role);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.users_id_seq, public.categories_id_seq, public.products_id_seq, public.pricing_rules_id_seq, public.stock_movements_id_seq, public.stock_requests_id_seq, public.price_history_id_seq FROM %I', client_role);
    END IF;
  END LOOP;
END;
$$;
